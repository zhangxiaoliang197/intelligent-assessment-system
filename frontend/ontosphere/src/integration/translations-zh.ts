export function translateUi(input: string): string {
  const normalized = input.replace(/\s+/g, ' ').trim();
  const exact = translations[input] ?? translations[normalized];
  if (exact) return input.replace(input.trim(), exact);
  if (/^(https?:|urn:|@prefix|PREFIX |SELECT |INSERT |DELETE |CONSTRUCT |ASK |\{)/.test(normalized)) return input;
  const dynamic: [RegExp, string][] = [
    [/^(Tooltips|Persisted autoload|Workflow catalog|Auto-load|Debug|RDF logging) (enabled|disabled)$/, '$1 $2'],
    [/^Loaded (\d+) shape file\(s\)$/, '已载入 $1 个约束文件'],
    [/^Showing page (\d+) of (\d+) — (\d+) triples$/, '第 $1 页，共 $2 页，$3 条三元组'],
    [/^(\d+) (triples|quads)$/, '$1 条三元组'],
    [/^(\d+) (classes|entities|nodes)$/, '$1 个节点'],
    [/^(\d+) (errors|warnings|inferences)$/, '$1 条结果'],
    [/^\(?(\d+) ms\)?$/, '$1 毫秒'],
    [/^Reasoning completed in (.+)$/, '推理已完成，用时 $1'],
    [/^Could not compute repairs:\s*(.*)$/, '无法计算修复方案：$1'],
    [/^Only the first (\d+) entities are shown,?\s*click here for the full results$/, '仅显示前 $1 个实体，点击查看全部结果'],
  ];
  for (const [pattern, replacement] of dynamic) if (pattern.test(normalized)) {
    let result = normalized.replace(pattern, replacement);
    result = result.replace(/^(Tooltips|Persisted autoload|Workflow catalog|Auto-load|Debug|RDF logging) (enabled|disabled)$/, (_, setting, enabled) => `${({ Tooltips: '操作提示', 'Persisted autoload': '启动自动加载', 'Workflow catalog': '工作流目录', 'Auto-load': '自动加载', Debug: '调试', 'RDF logging': '写入日志' } as Record<string,string>)[setting]}${enabled === 'enabled' ? '已启用' : '已关闭'}`);
    return input.replace(input.trim(), result);
  }
  return input;
}
